package java.io;
public class UnsupportedEncodingException extends IOException {
    public UnsupportedEncodingException() { super(); }
    public UnsupportedEncodingException(String s) { super(s); }
    public UnsupportedEncodingException(String s, Throwable cause) { super(s, cause); }
    public UnsupportedEncodingException(Throwable cause) { super(cause); }
}
