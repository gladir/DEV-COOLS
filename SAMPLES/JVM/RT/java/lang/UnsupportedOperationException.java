package java.lang;
public class UnsupportedOperationException extends RuntimeException {
    private static final long serialVersionUID = -1242599979055084673L;
    public UnsupportedOperationException() { super(); }
    public UnsupportedOperationException(String s) { super(s); }
    public UnsupportedOperationException(String s, Throwable cause) { super(s, cause); }
    public UnsupportedOperationException(Throwable cause) { super(cause); }
}
