package java.lang;
public class ReflectiveOperationException extends Exception {
    private static final long serialVersionUID = 123456789L;
    public ReflectiveOperationException() { super(); }
    public ReflectiveOperationException(String s) { super(s); }
    public ReflectiveOperationException(String s, Throwable cause) { super(s, cause); }
    public ReflectiveOperationException(Throwable cause) { super(cause); }
}
