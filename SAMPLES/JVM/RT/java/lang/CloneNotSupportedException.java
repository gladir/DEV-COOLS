package java.lang;
public class CloneNotSupportedException extends Exception {
    public CloneNotSupportedException() { super(); }
    public CloneNotSupportedException(String s) { super(s); }
    public CloneNotSupportedException(String s, Throwable cause) { super(s, cause); }
    public CloneNotSupportedException(Throwable cause) { super(cause); }
}
